#!/usr/bin/env python3
"""Rebuild display images and Jekyll dimensions; requires cwebp and identify."""

import subprocess
from pathlib import Path


DOCS = Path(__file__).resolve().parents[1] / "docs"
IMAGES = [
    # Source, maximum width (no upscaling), WebP quality.
    ("assets/images/courses/icon_aslo.jpg", 700, 85),
    ("assets/images/courses/icon_geodaten_data_lake.jpg", 700, 85),
    ("assets/images/courses/icon_PS_radar.jpg", 700, 85),
    ("assets/images/courses/icon_PS_RS.png", 700, 85),
    ("assets/images/courses/icon_meko.jpg", 700, 85),
    ("assets/images/courses/icon_SDM_2021.png", 700, 85),
    ("assets/images/courses/icon_data_analysis2021.png", 700, 85),
    ("assets/images/courses/icon_GeoAI.png", 700, 85),
    ("assets/images/courses/icon_advancedSDM.png", 700, 85),
    ("assets/images/courses/icon_remote_sensing.jpg", 700, 85),
    ("assets/images/courses/icon_upscaling.png", 700, 85),
    ("assets/images/courses/icon_proximate_sensing-min2.png", 700, 85),
    ("assets/images/courses/icon_R.png", 700, 85),
    ("assets/images/courses/icon_Python.png", 700, 85),
    ("assets/images/front_page/icon_philosophy.jpg", 700, 85),
    ("assets/images/front_page/icon_theses.jpg", 700, 85),
    ("assets/data/current/icons/icon_Ausschreibung_Masterarbeit_Phytoakmeter.png", 1200, 90),
    ("assets/data/current/icons/icon_Ausschreibung_Digitizer.jpg", 1200, 90),
    ("assets/data/current/icons/icon_Ausschreibung_Masterarbeit_Hainich.jpg", 1200, 90),
    ("assets/images/instructors/zeuss.jpg", 220, 85),
    ("assets/images/instructors/heidrich.jpg", 220, 85),
    ("assets/images/instructors/bald.jpg", 220, 85),
    ("assets/images/instructors/bhandari.jpeg", 220, 85),
    ("assets/images/instructors/forteva.jpg", 220, 85),
    ("assets/images/heroteaser/ChatGPT_1.jpg", 1792, 85),
    ("assets/images/heroteaser/heroteaser_6to1.jpg", 2400, 85),
]


def main():
    metadata = ["# Generated by scripts/optimize-images.py; do not edit by hand."]
    original_bytes = optimized_bytes = 0
    for source, maximum_width, quality in IMAGES:
        original = DOCS / source
        width, height = map(int, subprocess.check_output(
            ["identify", "-format", "%w %h", str(original)],
            universal_newlines=True,
        ).split())
        target_width = min(width, maximum_width)
        target_height = max(1, round(height * target_width / width))
        output = original.parent / "web" / (original.stem + ".webp")
        output.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([
            "cwebp", "-quiet", "-sharp_yuv", "-q", str(quality), "-m", "6",
            "-metadata", "none", "-resize", str(target_width), str(target_height),
            str(original), "-o", str(output),
        ], check=True)
        relative_output = output.relative_to(DOCS).as_posix()
        metadata.extend([
            relative_output + ":",
            "  source: " + source,
            "  width: " + str(target_width),
            "  height: " + str(target_height),
        ])
        original_bytes += original.stat().st_size
        optimized_bytes += output.stat().st_size
        print("{}: {:,} -> {:,} bytes".format(
            relative_output, original.stat().st_size, output.stat().st_size,
        ))
    (DOCS / "_data/image_derivatives.yml").write_text("\n".join(metadata) + "\n")
    print("Total: {:,} -> {:,} bytes".format(original_bytes, optimized_bytes))


if __name__ == "__main__":
    main()
